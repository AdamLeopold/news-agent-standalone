export function translateText(value, language = 'zh') {
  if (language !== 'en' || typeof value !== 'string') return value;
  const text = value.trim();
  if (!text) return value;
  let translated = Object.hasOwn(translations, text) ? translations[text] : undefined;
  if (translated === undefined) {
    for (const [pattern, render] of templates) {
      const match = text.match(pattern);
      if (match) {translated = render(...match); break;}
    }
  }
  if (translated === undefined) return value;
  const leading = value.match(/^\s*/)?.[0] || '';
  const trailing = value.match(/\s*$/)?.[0] || '';
  return leading + translated + trailing;
}

// Original source material is explicitly excluded from UI translation.
export function OriginalText({children, language}) {
  return React.createElement('span', {'data-original-text': '', ...(language ? {lang: language} : {})}, children);
}

export function translateNode(node, language) {
  if (typeof node === 'string') return translateText(node, language);
  if (Array.isArray(node)) return node.map(item => translateNode(item, language));
  if (!React.isValidElement(node) || node.type === OriginalText || language !== 'en') return node;
  const props = {};
  if (typeof node.type === 'string') {
    for (const key of ['title', 'aria-label', 'placeholder', 'alt']) {
      if (typeof node.props[key] === 'string') props[key] = translateText(node.props[key], language);
    }
  }
  if (node.props.children !== undefined) props.children = translateNode(node.props.children, language);
  return React.cloneElement(node, props);
}

