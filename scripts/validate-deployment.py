def now_iso():
    return datetime.now(timezone.utc).isoformat()


def sha(value):
    return hashlib.sha256(value if isinstance(value,bytes) else value.encode()).hexdigest()


def report_helper():
    spec=importlib.util.spec_from_file_location('ttf_live_smoke_report',ROOT/'scripts/repair-validation-report.py')
    if spec is None or spec.loader is None:raise RuntimeError('Report verification helper unavailable')
    module=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


REPORT=report_helper()


def protected_snapshot(database,manifest):
    # Do not instantiate Store: initialization performs migrations.
    uri='file:'+quote(str(database.resolve()),safe='/')+'?mode=ro'
    with sqlite3.connect(uri,uri=True,timeout=30) as connection:
        connection.row_factory=sqlite3.Row
        connection.execute('PRAGMA query_only=ON')
        return REPORT.verify_preservation(connection,manifest)


def require(value,message):
    if not value:raise ValueError(message)


def validate_forecast(result,detail=False):
    require(isinstance(result,dict),'No completed analysis result')
    # Persisted results carry the audited runtime envelope after model-schema
    # validation. Validate the model body separately, retaining the original
    # envelope for the strict version/evidence checks below.
    schema_body=copy.deepcopy(result)
    schema_body.pop('_meta',None)
    AnalysisResult.model_validate(schema_body)
    close=result.get('close_forecast') or {}
    require('evidence_status' in close,'v2 close_forecast.evidence_status is missing')
    if close['evidence_status']=='insufficient_evidence':
        require(close.get('direction') is None,'Insufficient evidence must retain direction=null')
    else:
        require(close['evidence_status']=='forecast' and close.get('direction') in LABELS and close.get('direction') is not None,'Invalid forecast contract')
    meta=result.get('_meta') or {}
    require(meta.get('prompt_version')==PROMPT_VERSION,'Forecast was generated by an earlier prompt version')
    require(meta.get('semantic_validation')=='bidirectional-v2' and meta.get('raw_evidence_validated') is True,'v2 raw evidence validation metadata missing')
    if detail:require(isinstance(result.get('detail'),dict),'Completed detail result is missing')
    return {'prompt_version':meta['prompt_version'],'news_direction':result['news_impact']['direction'],
            'close_direction':close.get('direction'),'close_evidence_status':close['evidence_status'],
            'english_close_label':LABELS[close.get('direction')],
            'summary_sha256':sha(str(close.get('summary') or '')),'summary_characters':len(str(close.get('summary') or '')),
            'model_seconds':meta.get('elapsed_seconds'),
            'as_of':meta.get('as_of'),'raw_evidence_validated':True}


def at_path(value,path):
    for part in path:value=value[part]
    return value


def protected_leaves(value,path=()):
    """Numbers, enums and citations must survive translation exactly."""
    if isinstance(value,dict):
        for key,row in value.items():
            if key=='_meta':continue
            if key in {'direction','evidence_status','confidence','contextual_news_score','signal_strength','id','url','references'}:
                yield path+(key,),row
            else:yield from protected_leaves(row,path+(key,))
    elif isinstance(value,list):
        for index,row in enumerate(value):yield from protected_leaves(row,path+(index,))
    elif isinstance(value,(int,float,bool)) or value is None:
        yield path,value


def validate_english(original,english):
    require(isinstance(english,dict),'English translation result missing')
    for path,value in protected_leaves(original):
        require(at_path(english,path)==value,'English translation changed a protected label, number or citation field')
    texts,_=prepare_translation(original)
    checked=[]
    for encoded in texts:
        path=json.loads(encoded)
        source=at_path(original,path)
        target=at_path(english,path)
        require(isinstance(target,str) and target.strip() and not CJK.search(target),'English analysis contains untranslated Chinese')
        require(re.search('[A-Za-z]',target),'English analysis has no English prose')
        require(Counter(PROTECTED.findall(source))==Counter(PROTECTED.findall(target)),'English narrative changed a number, date, citation or unit')
        checked.append(encoded)
    meta=english.get('_meta') or {}
    require(meta.get('output_language')=='en','English output_language metadata missing')
    require(meta.get('translation_source_sha256')==source_hash(original),'English rendering is not bound to this exact original result')
    return {'translated_fields_checked':len(checked),'protected_labels_numbers_citations_unchanged':True,
            'untranslated_chinese_fields':0,'source_sha256':source_hash(original),
            'news_direction':english['news_impact']['direction'],'close_direction':english['close_forecast'].get('direction'),
            'close_evidence_status':english['close_forecast']['evidence_status'],
            'english_close_label':LABELS[english['close_forecast'].get('direction')],
            'english_summary_sha256':sha(str(english['close_forecast'].get('summary') or '')),
            'english_summary_characters':len(str(english['close_forecast'].get('summary') or '')),
            'translation_model_seconds':meta.get('translation_elapsed_seconds')}


def real_manual_payload(article):
    require(article.get('id') and not str(article['id']).startswith(('manual-','synthetic-')),'Select an existing collected article')
    require(article.get('source') not in (None,'manual','手动输入','synthetic','test'),'Article source is not a real publisher')
    require(urlsplit(str(article.get('url') or '')).scheme in ('http','https'),'Real article source URL missing')
    parts=[]
    for key in ('summary','fact_excerpt'):
        text=str(article.get(key) or '').strip()
        if text and text not in parts:parts.append(text)
    body='\n\n'.join(parts)
    require(15<=len(body)<=30000,'Real article body does not fit the manual API; select another article')
    payload={'text':body,'title':str(article.get('title') or '')[:500],
             'source':str(article['source'])[:256],'published_at':article.get('published_at')}
    return payload


def parse_sse(lines):
    event={}
    for line in lines:
        if not line:
            if 'data' in event:
                yield {'id':int(event.get('id','0')),'event':event.get('event','message'),'data':json.loads(event['data'])}
            event={}
        elif not line.startswith(':') and ':' in line:
            key,value=line.split(':',1)
            event[key]=event.get(key,'')+('\n' if key=='data' and key in event else '')+value.lstrip()


class Smoke:
    def __init__(self,args):
        self.args=args
        self.deadline=time.monotonic()+args.timeout_seconds
        self.report={'status':'running','started_at':now_iso(),'expected_prompt_version':PROMPT_VERSION,
                     'scope':'real_local_manual_detail_english_exports_sse_and_preservation',
                     'synthetic_live_input':False,'raw_thinking_included':False,'stages':[]}
        self.client=httpx.AsyncClient(base_url=args.base_url,timeout=45,trust_env=False)

    def save(self):
        self.args.report.parent.mkdir(parents=True,exist_ok=True)
        safe=REPORT.safe(self.report)
        target=self.args.report.with_suffix(self.args.report.suffix+'.tmp')
        target.write_text(json.dumps(safe,ensure_ascii=False,indent=2,allow_nan=False)+'\n',encoding='utf-8')
        target.replace(self.args.report)

    def remaining(self):
        value=self.deadline-time.monotonic()
        if value<=0:raise TimeoutError('The overall live smoke test deadline was reached')
        return value

    async def request(self,method,path,**kwargs):
        response=await asyncio.wait_for(self.client.request(method,path,**kwargs),timeout=min(60,self.remaining()))
        response.raise_for_status()
        return response

    async def stage(self,name,operation):
        entry={'name':name,'status':'running','started_at':now_iso()}
        self.report['stages'].append(entry)
        started=time.monotonic()
        self.save()
        try:
            if name.startswith('preservation_'):
                value=await operation()
            else:
                budget=self.remaining()
                value=await asyncio.wait_for(operation(),timeout=budget)
            entry.update(status='passed',checks=value)
        except Exception as exc:
            value=None
            entry.update(status='failed',error_type=type(exc).__name__,error=REPORT.safe(str(exc)[:1200]))
        entry.update(finished_at=now_iso(),elapsed_seconds=round(time.monotonic()-started,3))
        self.save()
        print(json.dumps({'stage':name,'status':entry['status'],'elapsed_seconds':entry['elapsed_seconds']},ensure_ascii=False),flush=True)
        return value

    async def preserve(self):
        result=await asyncio.to_thread(protected_snapshot,self.args.db,self.manifest)
        require(result['passed'],'Original protected analysis/snapshot/validation hashes changed: '+json.dumps(result.get('failures',[])))
        return result

    async def readiness(self):
        health=(await self.request('GET','/api/health')).json()
        require(health.get('status')=='ok' and (health.get('model') or {}).get('available'),'Local model/backend health is unavailable')
        require(health.get('prompt_version')==PROMPT_VERSION,'Running API has not loaded the current v2 prompt')
        pid=int((ROOT/'.runtime/app.pid').read_text().strip())
        require(health.get('server_pid')==pid,'Health PID does not match the managed application PID')
        process=subprocess.run(['ps','-p',str(pid),'-o','args='],capture_output=True,text=True,timeout=5,check=True).stdout.strip()
        require('ttf_news.api:app' in process,'Managed PID is not the TTF application process')
        monitoring=(await self.request('GET','/api/monitoring')).json()
        return {'prompt_version':health['prompt_version'],'model':health.get('model',{}).get('model'),
                'server_pid':pid,'managed_pid_identity_verified':True,'collector':health.get('collector'),
                'counts':health.get('counts'),'monitoring_reachable':isinstance(monitoring,dict)}

    async def source(self):
        if self.args.news_id:
            items=[(await self.request('GET','/api/news/'+quote(self.args.news_id,safe=''))).json()]
        else:
            items=(await self.request('GET','/api/news?scope=recent&limit=100')).json().get('items',[])
        # Prefer public article prose over a structured capacity notice. Do not
        # invent a replacement if no real article satisfies the API contract.
        items.sort(key=lambda row:(row.get('source')=='gassco',not bool(row.get('fact_excerpt'))))
        for article in items:
            if article.get('is_premium'):continue
            try:payload=real_manual_payload(article)
            except ValueError:continue
            self.article=article;self.payload=payload
            return {'news_id':article['id'],'title':article.get('title'),'source':article['source'],
                    'url':article['url'],'published_at':article.get('published_at'),
                    'source_version':article.get('version'),'body_characters':len(payload['text']),
                    'body_sha256':sha(payload['text']),'fact_excerpt_used':bool(article.get('fact_excerpt'))}
        raise ValueError('No real nonpremium article with a usable body was available')

    async def ensure_current_v2_live(self):
        # This is the sole direct append operation. Recheck the live code
        # version before opening Store so an old backend cannot consume it.
        health=(await self.request('GET','/api/health')).json()
        require(health.get('status')=='ok' and health.get('prompt_version')==PROMPT_VERSION,
                'Do not append a version-update forecast until the restarted v2 backend is healthy')
        from ttf_news.store import Store
        from ttf_news.context import build_context
        from ttf_news.calendar import session_at,parse_time
        from ttf_news.analysis import _known
        moment=now_iso();session=session_at(moment)
        store=Store(self.args.db)
        with store.connection() as connection:
            rows=connection.execute("SELECT id,status,result,input_snapshot FROM analyses WHERE kind='live' AND trade_date=? ORDER BY created_at DESC",
                                    (session['trade_date'],)).fetchall()
        for row in rows:
            if 'brief' in ((store.analysis_review(row['id'],as_of=moment) or {}).get('invalid_parts') or []):
                continue
            result=json.loads(row['result']) if row['result'] else {}
            context=json.loads(row['input_snapshot']) if row['input_snapshot'] else {}
            completed_v2=row['status']=='completed' and (result.get('_meta') or {}).get('prompt_version')==PROMPT_VERSION
            requested_v2=row['status'] in ('queued','running') and context.get('requested_prompt_version')==PROMPT_VERSION
            if completed_v2 or requested_v2:
                self.live_analysis_id=row['id']
                return {'analysis_id':row['id'],'status':row['status'],'created':False,
                        'trade_date':session['trade_date'],'reason':'current_window_v2_already_exists'}
        known=[row for row in store.news(200,scope='recent') if _known(row,parse_time(moment))]
        require(known,'No genuinely known collected news is available for the current live outlook')
        trigger=max(known,key=lambda row:str(row.get('published_at') or row.get('first_seen_at') or ''))
        context=build_context(store,trigger,as_of=moment)
        context.update(analysis_kind='live',outlook_trigger='model_version_update',requested_prompt_version=PROMPT_VERSION)
        created=store.create_analysis(context,kind='live',priority=3)
        self.live_analysis_id=created['id'];self.report['new_live_analysis_id']=created['id']
        return {'analysis_id':created['id'],'status':created['status'],'created':True,
                'trade_date':session['trade_date'],'source_news_id':trigger['id'],
                'reason':'append_fresh_version_update_forecast','priority':3,
                'old_forecasts_overwritten':False,'validation_baseline_reset':False}

    async def sse(self,cursor=None,analysis_id=None,event_type=None,query=False):
        headers={}
        path='/api/stream'
        if cursor is not None:
            if query:path+='?after='+str(cursor)
            else:headers['Last-Event-ID']=str(cursor)
        deadline=min(self.deadline,time.monotonic()+45)
        seen=[];buffer=[]
        async with self.client.stream('GET',path,headers=headers,timeout=httpx.Timeout(50,read=10)) as response:
            response.raise_for_status()
            require('text/event-stream' in response.headers.get('content-type',''),'SSE media type missing')
            async for line in response.aiter_lines():
                if time.monotonic()>deadline:raise TimeoutError('SSE expected replay did not arrive')
                buffer.append(line)
                if line:continue
                for event in parse_sse(buffer):
                    data=event['data']
                    if cursor is not None:require(event['id']>cursor,'SSE replay included an already acknowledged event')
                    require(event['id'] not in seen,'SSE replay repeated an event ID')
                    seen.append(event['id'])
                    if (analysis_id is None or data.get('id')==analysis_id) and (event_type is None or data.get('type')==event_type):
                        return {'id':event['id'],'type':data.get('type'),'kind':data.get('kind'),
                                'matched_analysis_id':data.get('id'),'replayed_event_count':len(seen),
                                'cursor_mode':'after_query' if query else 'Last-Event-ID' if cursor is not None else 'initial_ready'}
                buffer=[]
        raise RuntimeError('SSE disconnected before the expected event')

    async def submit_manual(self):
        value=(await self.request('POST','/api/manual/analyze',json=self.payload)).json()
        require(value.get('id') and value.get('status') in ('queued','running'),'Manual analysis was not queued')
        self.analysis_id=value['id'];self.report['new_analysis_id']=value['id']
        return {'analysis_id':value['id'],'status':value['status'],'real_source_news_id':self.article['id']}

    async def poll_analysis(self,detail=False):
        polls=0;progress=time.monotonic()
        while True:
            self.remaining()
            record=(await self.request('GET','/api/analyses/'+self.analysis_id+'?include_input=true')).json()
            field='detail_status' if detail else 'status'
            status=record.get(field)
            if status=='failed':raise RuntimeError(('Detail' if detail else 'Brief')+' failed: '+str(record.get('detail_error' if detail else 'error'))[:900])
            if status=='completed':
                require(record.get('kind')=='manual','Smoke analysis was not stored independently as manual')
                require(record['input_snapshot']['current_news']['summary']==self.payload['text'],'Stored manual source body differs from the real article text submitted')
                result=record['detail_result' if detail else 'result']
                summary=validate_forecast(result,detail)
                summary.update(analysis_id=self.analysis_id,poll_count=polls,
                               completed_at=record.get('completed_at'),source_body_unchanged=True)
                if detail:self.detail=result
                else:self.brief=result
                return summary
            require(status in ('queued','running','not_requested'),'Unexpected analysis lifecycle state: '+str(status))
            if time.monotonic()-progress>=30:
                print(json.dumps({'waiting':'detail' if detail else 'brief','status':status,'polls':polls}),flush=True);progress=time.monotonic()
            polls+=1
            await asyncio.sleep(min(4,self.remaining()))

    async def request_detail(self):
        return (await self.request('POST','/api/analyses/'+self.analysis_id+'/detail',json={})).json()

    async def translate(self,part):
        value=(await self.request('POST','/api/analyses/'+self.analysis_id+'/translation?part='+part,json={})).json()
        require(value.get('id'),'English rendering was not queued')
        self.translation_ids[part]=value['id']
        return {'translation_id':value['id'],'part':part,'status':value.get('status')}

    async def poll_translation(self,part):
        identifier=self.translation_ids[part];polls=0;progress=time.monotonic()
        while True:
            self.remaining()
            record=(await self.request('GET','/api/translations/'+identifier)).json()
            status=record.get('status')
            if status=='failed':raise RuntimeError('English '+part+' failed: '+str(record.get('error'))[:900])
            if status=='completed':
                original=self.detail if part=='detail' else self.brief
                summary=validate_english(original,record.get('result'))
                cached=(await self.request('GET','/api/analyses/'+self.analysis_id+'/translation?part='+part)).json()
                require(cached.get('id')==identifier and cached.get('status')=='completed','English cache endpoint does not return the completed rendering')
                summary.update(translation_id=identifier,part=part,poll_count=polls,cache_endpoint_verified=True)
                return summary
            require(status in ('queued','running'),'Unexpected translation lifecycle state')
            if time.monotonic()-progress>=30:
                print(json.dumps({'waiting':'english_'+part,'status':status,'polls':polls}),flush=True);progress=time.monotonic()
            polls+=1
            await asyncio.sleep(min(4,self.remaining()))

    async def source_results_unchanged(self):
        record=(await self.request('GET','/api/analyses/'+self.analysis_id)).json()
        require(source_hash(record['result'])==source_hash(self.brief),'English rendering changed the original Chinese brief')
        require(source_hash(record['detail_result'])==source_hash(self.detail),'English rendering changed the original Chinese detail')
        return {'brief_sha256':source_hash(self.brief),'detail_sha256':source_hash(self.detail),
                'original_chinese_results_unchanged':True,
                'detail_direction_change':self.brief['close_forecast'].get('direction')!=self.detail['close_forecast'].get('direction')}

    async def exports(self):
        result={}
        for dataset,required in (('news',{'id','url','source'}),('daily',{'trade_date','news_ids'}),
                                 ('events',{'id'}),('prices',{'contract','day','value','price_type'})):
            formats={}
            for extension in ('csv','jsonl'):
                response=await self.request('GET','/api/export/'+dataset+'.'+extension)
                content=response.content
                require(content,'Empty export response: '+dataset+'.'+extension)
                require('attachment' in response.headers.get('content-disposition',''),'Export attachment header missing')
                text=content.decode('utf-8-sig')
                if extension=='jsonl':rows=[json.loads(line) for line in text.split('\n') if line.strip()]
                else:rows=list(csv.DictReader(io.StringIO(text)))
                require(rows and required.issubset(rows[0]),'Export rows/schema missing: '+dataset+'.'+extension)
                if dataset=='news' and extension=='jsonl':require(any(row.get('id')==self.article['id'] for row in rows),'Selected real source article is missing from news export')
                formats[extension]={'rows':len(rows),'bytes':len(content),'sha256':sha(content),'parsed':True}
            formats['row_counts_match']=formats['csv']['rows']==formats['jsonl']['rows']
            # Collection can add real rows between the two independent requests.
            formats['independent_snapshot_requests']=True
            result[dataset]=formats
        return result

    async def current_forecast(self):
        last_error='No current completed live outlook'
        while True:
            self.remaining()
            dashboard=(await self.request('GET','/api/dashboard')).json()
            live=dashboard.get('latest_analysis') or {}
            try:
                summary=validate_forecast(live.get('result'))
                require(live.get('kind')=='live' and live.get('trade_date')==dashboard.get('session',{}).get('trade_date'),'Dashboard forecast is not the current live settlement window')
                summary.update(analysis_id=live['id'],trade_date=live['trade_date'],dashboard_current_window_verified=True)
                return summary
            except ValueError as exc:last_error=str(exc)
            if self.remaining()<8:raise RuntimeError('Current dashboard forecast did not reach v2: '+last_error)
            await asyncio.sleep(min(5,self.remaining()))

    async def run(self):
        self.manifest=json.loads(self.args.manifest.read_text())
        self.translation_ids={}
        self.save()
        try:
            preservation=await self.stage('preservation_before',self.preserve)
            ready=await self.stage('live_api_v2_and_managed_identity',self.readiness) if preservation else None
            source=await self.stage('select_real_existing_news',self.source) if ready else None
            if source:await self.stage('ensure_current_v2_live_forecast',self.ensure_current_v2_live)
            initial=await self.stage('sse_initial_connection',self.sse) if source else None
            submitted=await self.stage('manual_submit_real_news',self.submit_manual) if initial else None
            if submitted:
                await self.stage('sse_last_event_id_reconnect',lambda:self.sse(initial['id'],self.analysis_id,'analysis_queued'))
                await self.stage('sse_after_query_reconnect',lambda:self.sse(initial['id'],self.analysis_id,'analysis_queued',True))
                brief=await self.stage('manual_real_brief',self.poll_analysis)
                if brief:
                    await self.stage('sse_completed_event_replay',lambda:self.sse(initial['id'],self.analysis_id,'analysis_completed'))
                    detail_request=await self.stage('manual_detail_request',self.request_detail)
                    english_brief=await self.stage('english_brief_request',lambda:self.translate('brief'))
                    detail=await self.stage('manual_real_detail',lambda:self.poll_analysis(True)) if detail_request else None
                    english_detail=await self.stage('english_detail_request',lambda:self.translate('detail')) if detail else None
                    if english_brief:await self.stage('english_brief_actual_text_labels_numbers',lambda:self.poll_translation('brief'))
                    if english_detail:await self.stage('english_detail_actual_text_labels_numbers',lambda:self.poll_translation('detail'))
                    if detail:await self.stage('chinese_originals_unchanged_after_translation',self.source_results_unchanged)
            if source:await self.stage('csv_jsonl_exports',self.exports)
            if ready:await self.stage('current_live_forecast_v2',self.current_forecast)
        finally:
            await self.stage('preservation_after',self.preserve)
            await self.client.aclose()
            required={'preservation_before','live_api_v2_and_managed_identity','select_real_existing_news',
                      'ensure_current_v2_live_forecast',
                      'sse_initial_connection','manual_submit_real_news','sse_last_event_id_reconnect',
                      'sse_after_query_reconnect','manual_real_brief','sse_completed_event_replay','manual_detail_request',
                      'manual_real_detail','english_brief_actual_text_labels_numbers','english_detail_actual_text_labels_numbers',
                      'chinese_originals_unchanged_after_translation','csv_jsonl_exports','current_live_forecast_v2','preservation_after'}
            passed={entry['name'] for entry in self.report['stages'] if entry['status']=='passed'}
            failed=[entry['name'] for entry in self.report['stages'] if entry['status']=='failed']
            self.report.update(status='passed' if required.issubset(passed) and not failed else 'failed',
                               finished_at=now_iso(),failed_stages=failed,missing_required_stages=sorted(required-passed),
                               elapsed_seconds=round(self.args.timeout_seconds-(self.deadline-time.monotonic()),3))
            self.save()
        return 0 if self.report['status']=='passed' else 1


